/** i18n key for a catalog item id, e.g. selector-2 → comp.selector2 */
export function catalogCompKey(id: string): string {
  const mapped = COMP_KEY[id];
  if (mapped) return `comp.${mapped}`;
  const camel = id.replace(/-([a-z0-9])/gi, (_, c: string) => c.toUpperCase());
  return `comp.${camel}`;
}

function interpolate(msg: string, params?: Record<string, string | number>): string {
  if (!params) return msg;
  return msg.replace(/\{(\w+)\}/g, (_, name) => {
    const val = params[name];
    return val !== undefined ? String(val) : `{${name}}`;
  });
}

export function t(key: string, params?: Record<string, string | number>): string {
  const msg = TRANSLATIONS[getLang()][key];
  if (!msg) return key;
  return interpolate(msg, params);
}

/** Like t(), but uses fallback instead of echoing a missing key. */
export function tOr(key: string, fallback: string, params?: Record<string, string | number>): string {
  const msg = TRANSLATIONS[getLang()][key];
  if (!msg) return fallback;
  return interpolate(msg, params);
}

export function formatFaultMessage(f: { level?: "warn" | "error"; message: string; msgKey?: string; msgParams?: Record<string, string | number> }): string {
  if (f.msgKey) {
    return t(f.msgKey, f.msgParams);
  }
  return f.message;
}
